namespace ct = cuda::tiles;

// This is intentionally a small, parallel-beam reconstruction. An asymmetric
// tetrahedron is observed at 256 in-plane angles. Each angle has a 32x32
// detector: u is the rotating in-plane detector coordinate and v is parallel
// to the volume's z axis. The source projections are analytic line integrals,
// rather than samples generated by a separate forward-projection kernel.
constexpr size_t volume_extent = 16;
constexpr size_t detector_extent = 32;
constexpr size_t projection_count = 256;
constexpr size_t z_slab_extent = 4;
constexpr size_t detector_pixels = detector_extent * detector_extent;
constexpr size_t projection_elements = projection_count * detector_pixels;
constexpr size_t volume_elements = volume_extent * volume_extent * volume_extent;
constexpr float pi = 3.14159265358979323846f;
constexpr size_t detector_v_offset = (detector_extent - volume_extent) / 2;
static_assert(volume_extent % z_slab_extent == 0, "z slabs must cover the volume exactly");

constexpr size_t projection_offset(size_t projection, size_t v, size_t u) {
    return (projection * detector_extent + v) * detector_extent + u;
}

__host__ __device__ constexpr size_t volume_offset(size_t z, size_t y, size_t x) {
    return (z * volume_extent + y) * volume_extent + x;
}


struct point3 {
    float x;
    float y;
    float z;
};
constexpr point3 add(point3 lhs, point3 rhs) {
    return { lhs.x + rhs.x, lhs.y + rhs.y, lhs.z + rhs.z };
}


constexpr point3 subtract(point3 lhs, point3 rhs) {
    return { lhs.x - rhs.x, lhs.y - rhs.y, lhs.z - rhs.z };
}

constexpr point3 scale(point3 value, float factor) {
    return { value.x * factor, value.y * factor, value.z * factor };
}

constexpr float dot(point3 lhs, point3 rhs) {
    return lhs.x * rhs.x + lhs.y * rhs.y + lhs.z * rhs.z;
}

constexpr point3 cross(point3 lhs, point3 rhs) {
    return { lhs.y * rhs.z - lhs.z * rhs.y, lhs.z * rhs.x - lhs.x * rhs.z, lhs.x * rhs.y - lhs.y * rhs.x };
}

// The vertices are deliberately asymmetric so the angle-dependent projections
// and the saved Python reconstruction image expose coordinate/layout mistakes.
constexpr std::array<point3, 4> tetrahedron_vertices { point3 { -4.5f, -3.5f, -4.0f },
                                                       point3 { 4.5f, -2.5f, -3.5f },
                                                       point3 { -2.5f, 4.5f, -2.5f },
                                                       point3 { 1.5f, 1.0f, 5.0f } };

float tetrahedron_ray_length(point3 origin, point3 direction) {
    constexpr std::array<std::array<size_t, 4>, 4> faces {
        std::array<size_t, 4> { 1, 2, 3, 0 },
        std::array<size_t, 4> { 0, 3, 2, 1 },
        std::array<size_t, 4> { 0, 1, 3, 2 },
        std::array<size_t, 4> { 0, 2, 1, 3 },
    };
    constexpr float epsilon = 1e-6f;
    float t_min = -1e20f;
    float t_max = 1e20f;
    for (const auto& face : faces) {
        const point3& first = tetrahedron_vertices[face[0]];
        point3 normal =
            cross(subtract(tetrahedron_vertices[face[1]], first), subtract(tetrahedron_vertices[face[2]], first));
        if (dot(normal, subtract(tetrahedron_vertices[face[3]], first)) > 0.0f) {
            normal = scale(normal, -1.0f);
        }
        const float direction_coefficient = dot(normal, direction);
        const float origin_coefficient = dot(normal, subtract(origin, first));
        if (std::abs(direction_coefficient) <= epsilon) {
            if (origin_coefficient > 0.0f) return 0.0f;
            continue;
        }
        const float boundary = -origin_coefficient / direction_coefficient;
        if (direction_coefficient > 0.0f) {
            t_max = std::min(t_max, boundary);
        } else {
            t_min = std::max(t_min, boundary);
        }
    }
    return std::max(0.0f, t_max - t_min);
}

// One Tile CTA owns a [4,16,16] z slab. For every view it filters
// the four detector rows needed by that slab and synthesizes the two nonzero
// bilinear weights for every [y,x] voxel directly from the detector geometry.
// The reduction over u is consequently both the detector gather and the
// voxel-driven backprojection; neither weights nor filtered rows use global
// memory.
__tile_global__ void fused_filtered_backprojection_kernel(const float* projections,
                                                          const float* frequency_response,
                                                          const float* view_cosines,
                                                          const float* view_sines,
                                                          float* reconstruction) {
    const size_t slab = ct::bid().x;
    using detector_rows_shape = ct::shape<z_slab_extent, detector_extent>;
    using response_shape = ct::shape<1, detector_extent, 1>;
    using weights_shape = ct::shape<1, volume_extent, volume_extent, detector_extent>;
    using voxel_slab_shape = ct::shape<z_slab_extent, volume_extent, volume_extent>;
    using y_indices_shape = ct::shape<1, volume_extent, 1, 1>;
    using x_indices_shape = ct::shape<1, 1, volume_extent, 1>;
    using u_indices_shape = ct::shape<1, 1, 1, detector_extent>;
    using scalar_shape = ct::shape<1>;
    using weights_tile = ct::tile<float, weights_shape>;

    auto response_view =
        ct::partition_view { ct::tensor_span { ct::assume_aligned<16>(frequency_response), response_shape {} },
                             response_shape {} };
    const auto volume_center = 0.5f * static_cast<float>(volume_extent - 1);
    const auto detector_center = 0.5f * static_cast<float>(detector_extent - 1);
    const auto y_coordinates = ct::element_cast<float>(ct::iota<ct::tile<int, y_indices_shape>>()) - volume_center;
    const auto x_coordinates = ct::element_cast<float>(ct::iota<ct::tile<int, x_indices_shape>>()) - volume_center;
    const auto u_indices = ct::iota<ct::tile<int, u_indices_shape>>();
    const auto zero_weights = ct::zeros<weights_tile>();
    auto accumulated = ct::full<ct::tile<float, voxel_slab_shape>>(0.0f);
    for (size_t projection = 0; projection < projection_count; ++projection) {
        const size_t first_row = slab * z_slab_extent + detector_v_offset;
        const size_t projection_row_offset = (projection * detector_extent + first_row) * detector_extent;
        const auto detector_rows_view =
            ct::partition_view { ct::tensor_span { ct::assume_aligned<16>(projections + projection_row_offset),
                                                   detector_rows_shape {} },
                                 detector_rows_shape {} };

        // Workaround for a compiler issue: disable TMA for this load and the
        // reconstruction store.
        [[cutile::hint(0, allow_tma = false)]] const auto detector_rows = detector_rows_view.load(0, 0);
        const auto spectrum = cufftdx::tiles::rfft(detector_rows, cufftdx::tiles::axis<1>, cufftdx::tiles::full);
        const auto response = response_view.load(0, 0, 0);
        const auto real = ct::extract(spectrum, ct::shape<z_slab_extent, detector_extent, 1> {}, 0, 0, 0);
        const auto imag = ct::extract(spectrum, ct::shape<z_slab_extent, detector_extent, 1> {}, 0, 0, 1);
        const auto filtered_spectrum = ct::cat<2>(real * response, imag * response);
        const auto filtered_rows =
            cufftdx::tiles::irfft(filtered_spectrum, cufftdx::tiles::axis<1>, cufftdx::tiles::full) *
            (1.0f / static_cast<float>(detector_extent));

        const auto cosine_view =
            ct::partition_view { ct::tensor_span { ct::assume_aligned<4>(view_cosines + projection), scalar_shape {} },
                                 scalar_shape {} };
        const auto sine_view =
            ct::partition_view { ct::tensor_span { ct::assume_aligned<4>(view_sines + projection), scalar_shape {} },
                                 scalar_shape {} };
        const auto cosine = ct::reshape(cosine_view.load(0), ct::shape<1, 1, 1, 1> {});
        const auto sine = ct::reshape(sine_view.load(0), ct::shape<1, 1, 1, 1> {});
        const auto detector_u = x_coordinates * cosine + y_coordinates * sine + detector_center;
        // The 16^3 volume is centered in a 32-wide detector, so each u0 and
        // u0 + 1 pair is in range. Converting positive detector coordinates
        // to int therefore implements floor for this geometry.
        const auto u0 = ct::element_cast<int>(detector_u);
        const auto du = detector_u - ct::element_cast<float>(u0);
        const auto du_expanded = ct::full<weights_tile>(0.0f) + du;
        const auto weights = ct::select(u_indices == u0, ct::full<weights_tile>(1.0f) - du_expanded, zero_weights) +
                             ct::select(u_indices == u0 + 1, du_expanded, zero_weights);
        const auto weighted_rows =
            ct::reshape(filtered_rows, ct::shape<z_slab_extent, 1, 1, detector_extent> {}) * weights;
        accumulated =
            accumulated + ct::reshape(ct::sum(weighted_rows, ct::integral_constant<3> {}), voxel_slab_shape {});
    }

    auto reconstruction_view = ct::partition_view {
        ct::tensor_span { ct::assume_aligned<16>(reconstruction + slab * z_slab_extent * volume_extent * volume_extent),
                          voxel_slab_shape {} },
        voxel_slab_shape {}
    };
    [[cutile::hint(0, allow_tma = false)]] reconstruction_view.store(
        accumulated * (pi / static_cast<float>(projection_count)), 0, 0, 0);
}

void generate_tetrahedron_projections(std::vector<float>& projections) {
    const float detector_center = 0.5f * static_cast<float>(detector_extent - 1);
    for (size_t projection = 0; projection < projection_count; ++projection) {
        const float angle = pi * static_cast<float>(projection) / static_cast<float>(projection_count);
        const point3 u_axis { cosf(angle), sinf(angle), 0.0f };
        const point3 ray_direction { -sinf(angle), cosf(angle), 0.0f };
        for (size_t v = 0; v < detector_extent; ++v) {
            const float detector_v = static_cast<float>(v) - detector_center;
            for (size_t u = 0; u < detector_extent; ++u) {
                const float detector_u = static_cast<float>(u) - detector_center;
                const point3 ray_origin = add(scale(u_axis, detector_u), { 0.0f, 0.0f, detector_v });
                projections[projection_offset(projection, v, u)] = tetrahedron_ray_length(ray_origin, ray_direction);
            }
        }
    }
}

bool all_finite(const std::vector<float>& values) {
    for (size_t index = 0; index < values.size(); ++index) {
        if (!std::isfinite(values[index])) {
            std::fprintf(stderr, "non-finite reconstruction value at index %zu: %g\n", index, values[index]);
            return false;
        }
    }
    return true;
}

int main() {
    std::vector<float> projections(projection_elements);
    std::vector<float> frequency_response(detector_extent);
    std::vector<float> view_cosines(projection_count);
    std::vector<float> view_sines(projection_count);
    std::vector<float> reconstruction(volume_elements);
    generate_tetrahedron_projections(projections);

    // The discrete Ram-Lak (ramp) response is |k| / N in full [0, N)
    // RFFT-bin order. Bins above N/2 encode the negative frequencies.
    for (size_t frequency = 0; frequency < detector_extent; ++frequency) {
        const int signed_frequency = frequency <= detector_extent / 2 ? static_cast<int>(frequency)
                                                                      : static_cast<int>(frequency) - detector_extent;
        frequency_response[frequency] =
            std::abs(static_cast<float>(signed_frequency)) / static_cast<float>(detector_extent);
    }
    for (size_t projection = 0; projection < projection_count; ++projection) {
        const float angle = pi * static_cast<float>(projection) / static_cast<float>(projection_count);
        view_cosines[projection] = std::cos(angle);
        view_sines[projection] = std::sin(angle);
    }

    mathdx_examples::device_buffer<float> device_projections(projections.size());
    mathdx_examples::device_buffer<float> device_frequency_response(frequency_response.size());
    mathdx_examples::device_buffer<float> device_view_cosines(view_cosines.size());
    mathdx_examples::device_buffer<float> device_view_sines(view_sines.size());
    mathdx_examples::device_buffer<float> device_reconstruction(reconstruction.size());
    device_projections.copy_from_host(projections.data(), projections.size());
    device_frequency_response.copy_from_host(frequency_response.data(), frequency_response.size());
    device_view_cosines.copy_from_host(view_cosines.data(), view_cosines.size());
    device_view_sines.copy_from_host(view_sines.data(), view_sines.size());

    cudaEvent_t start = nullptr;
    cudaEvent_t stop = nullptr;
    CUDA_CHECK(cudaEventCreate(&start));
    CUDA_CHECK(cudaEventCreate(&stop));
    CUDA_CHECK(cudaEventRecord(start));
    fused_filtered_backprojection_kernel<<<volume_extent / z_slab_extent, 1>>>(device_projections.data(),
                                                                               device_frequency_response.data(),
                                                                               device_view_cosines.data(),
                                                                               device_view_sines.data(),
                                                                               device_reconstruction.data());
    CUDA_CHECK(cudaEventRecord(stop));
    CUDA_CHECK(cudaEventSynchronize(stop));
    float fused_ms = 0.0f;
    CUDA_CHECK(cudaEventElapsedTime(&fused_ms, start, stop));
    CUDA_CHECK(cudaGetLastError());
    device_reconstruction.copy_to_host(reconstruction.data(), reconstruction.size());
    CUDA_CHECK(cudaEventDestroy(start));
    CUDA_CHECK(cudaEventDestroy(stop));

    const float center_value = reconstruction[volume_offset(volume_extent / 2, volume_extent / 2, volume_extent / 2)];
    std::printf("3D ramp-filtered backprojection: %zux%zux%zu volume from %zu %zux%zu projections\n",
                volume_extent,
                volume_extent,
                volume_extent,
                projection_count,
                detector_extent,
                detector_extent);
    std::printf("center voxel = %.6g; fused Tile voxel-driven = %.3f ms\n", center_value, fused_ms);
    return all_finite(reconstruction) && center_value > 0.0f ? EXIT_SUCCESS : EXIT_FAILURE;
}
